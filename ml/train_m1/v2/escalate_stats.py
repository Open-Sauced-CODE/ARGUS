"""H6 numbers: escalate true/false positives and negatives per generator, set and rule, from the harvest files.

    python -m ml.train_m1.v2.escalate_stats

Reads  ml/train_m2/contract/harvest_inputs.jsonl (which sets each input belongs to, with counts),
       ml/README_contracts.md (the route table: T0 / M1 / ESC per rule),
       ml/train_m2/harvest_out/<generator>/A/ (sample 0 = the greedy answer, the one Phase 5 scored as pass@1).
Writes docs/proposals/escalate-stats.md (and prints it). Every number in docs/proposals/escalate-router.md comes from here.

Definitions: a case is an (input, set) pair weighted by how many dataset examples share that input in that set.
  ESC case   = the rule's route is ESC (the correct answer is the escalate operation)
  tp         = ESC case and the answer is escalate-only         fn = ESC case and the answer is anything else
  fp         = fix case (route T0 or M1) and the answer is escalate-only
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from ml.train_m2.harvest.paths import DEFAULT_OUT, INPUTS_PATH, REPO_ROOT
from ml.train_m2.harvest.store import iter_lines

CONTRACTS = REPO_ROOT / "ml" / "README_contracts.md"
DEFAULT_REPORT = REPO_ROOT / "docs" / "proposals" / "escalate-stats.md"
SET_ORDER = ("train", "A_val", "B1", "B2", "C_verifier", "gold")
GENERATORS = ("zeroshot", "sft", "rft", "rft_v2")


def route_table(path: Path = CONTRACTS) -> Dict[str, str]:
    """{rule_id: 'T0' | 'M1' | 'ESC'} parsed from the rule table of ml/README_contracts.md."""
    lines = Path(path).read_text(encoding="utf-8-sig").splitlines()
    start = next((i for i, line in enumerate(lines) if line.startswith("| Rule ID |")), None)
    if start is None:
        raise ValueError("rule table (header '| Rule ID |') not found in %s" % path)
    header = [c.strip() for c in lines[start].strip().strip("|").split("|")]
    routes: Dict[str, str] = {}
    for line in lines[start + 2:]:
        if not line.startswith("|"):
            break
        row = dict(zip(header, [c.strip() for c in line.strip().strip("|").split("|")]))
        routes[row["Rule ID"].strip("`")] = row["Route"]
    return routes


def is_escalate(content: Optional[str]) -> bool:
    """True when the answer is JSON whose ops are all `escalate` (and there is at least one)."""
    if not content:
        return False
    try:
        data = json.loads(content)
        ops = data["ops"]
        return isinstance(ops, list) and bool(ops) and all(isinstance(o, dict) and o.get("op") == "escalate" for o in ops)
    except (ValueError, KeyError, TypeError):
        return False


def compute(inputs: Sequence[Dict[str, Any]], routes: Dict[str, str], answers: Dict[str, Dict[str, Optional[str]]]) -> Dict[str, Any]:
    """answers[generator][input_key] = greedy content (None if missing or failed)."""
    per_set: Dict[str, Dict[str, Dict[str, int]]] = {}
    per_rule: Dict[str, Dict[str, Dict[str, int]]] = {}
    for generator, by_key in answers.items():
        sets: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
        rules: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
        for item in inputs:
            rule = item["record"]["rule_id"]
            if rule not in routes:
                raise ValueError("rule %s is not in the contracts route table" % rule)
            esc_ref = routes[rule] == "ESC"
            content = by_key.get(item["input_key"])
            escalated = is_escalate(content)
            for set_name, weight in item.get("sets", {}).items():
                s = sets[set_name]
                if content is None:
                    s["no_answer"] += weight
                if esc_ref:
                    s["esc_cases"] += weight
                    s["tp" if escalated else "fn"] += weight
                else:
                    s["fix_cases"] += weight
                    if escalated:
                        s["fp"] += weight
            r = rules[rule]
            r["cases"] += 1
            r["escalated"] += 1 if escalated else 0
        per_set[generator] = {k: dict(v) for k, v in sets.items()}
        per_rule[generator] = {k: dict(v) for k, v in rules.items()}
    return {"per_set": per_set, "per_rule": per_rule, "routes": routes}


def _rate(num: int, den: int) -> str:
    return "n/a" if den == 0 else "%.3f" % (num / den)


def to_markdown(result: Dict[str, Any]) -> str:
    out: List[str] = ["# Escalate statistics (generated by `python -m ml.train_m1.v2.escalate_stats`)", "",
                      "Greedy answer (sample 0), profile A harvest. Cases are weighted by dataset examples per set.", ""]
    for generator, sets in result["per_set"].items():
        out += ["## %s" % generator, "",
                "| Set | ESC cases | tp | fn | recall | fix cases | fp | fp rate | no answer |", "|---|---|---|---|---|---|---|---|---|"]
        for name in [s for s in SET_ORDER if s in sets] + sorted(s for s in sets if s not in SET_ORDER):
            s = sets[name]
            g = lambda k: s.get(k, 0)  # noqa: E731
            out.append("| %s | %d | %d | %d | %s | %d | %d | %s | %d |" % (
                name, g("esc_cases"), g("tp"), g("fn"), _rate(g("tp"), g("esc_cases")), g("fix_cases"), g("fp"),
                _rate(g("fp"), g("fix_cases")), g("no_answer")))
        out.append("")
    out += ["## Per ESC rule (distinct inputs; how many were answered with escalate)", "",
            "| Generator | Rule | Distinct inputs | Escalated |", "|---|---|---|---|"]
    for generator, rules in result["per_rule"].items():
        for rule in sorted(rules):
            if result["routes"].get(rule) == "ESC":
                out.append("| %s | %s | %d | %d |" % (generator, rule, rules[rule]["cases"], rules[rule]["escalated"]))
    return "\n".join(out) + "\n"


def load_answers(root: Path, generator: str) -> Optional[Dict[str, Optional[str]]]:
    folder = Path(root) / generator / "A"
    if not folder.is_dir():
        return None
    answers: Dict[str, Optional[str]] = {}
    for _path, line in iter_lines(folder):
        if line["sample_idx"] == 0:
            answers[line["input_key"]] = None if line["error"] is not None else line["content"]
    return answers


def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--harvest", type=Path, default=DEFAULT_OUT)
    p.add_argument("--inputs", type=Path, default=INPUTS_PATH)
    p.add_argument("--contracts", type=Path, default=CONTRACTS)
    p.add_argument("--out", type=Path, default=DEFAULT_REPORT)
    args = p.parse_args(list(sys.argv[1:] if argv is None else argv))
    inputs = [json.loads(raw) for raw in args.inputs.read_bytes().decode("utf-8").splitlines() if raw.strip()]
    answers = {g: a for g in GENERATORS for a in [load_answers(args.harvest, g)] if a is not None}
    if not answers:
        print("No harvest folders found under %s" % args.harvest)
        return 2
    text = to_markdown(compute(inputs, route_table(args.contracts), answers))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("ascii", "replace"))
    print(text)
    print("Saved to %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
